// File: scripts/evidence.mjs · Node 22+ ESM
// Turns the rows the test suites append to docs/evidence/.rows-<target>.jsonl into the evidence file
//   docs/evidence/matrix-<target>-<date>.md   (one row per test: persona, attempt, HTTP/Parse code,
//                                              body assertion, state assertion)
// Wired into npm: `pretest` runs `--reset` (start a fresh collection), `posttest` writes the file, so the
// committed evidence always reflects ONE complete `npm test` run. Run dates use the local machine's date.
import { readFileSync, writeFileSync, rmSync, existsSync, readdirSync } from 'node:fs';
import path from 'node:path';
import { ROOT, args } from './lib/env.mjs';

const EVIDENCE_DIR = path.join(ROOT, 'docs', 'evidence');
// Same target labeling as test/helpers.mjs: evidence is labeled by what it actually ran against.
const TARGET = !process.env.TEST_SERVER_URL ? 'local'
  : /back4app\.com/.test(process.env.TEST_SERVER_URL) ? 'back4app' : 'remote-rehearsal';
const ROWS_FILE = path.join(EVIDENCE_DIR, `.rows-${TARGET}.jsonl`);
const a = args();

if (a.reset) {
  rmSync(ROWS_FILE, { force: true });
  process.exit(0);
}

if (!existsSync(ROWS_FILE)) {
  console.error(`evidence: no .rows-${TARGET}.jsonl — run \`npm test\` first.`);
  process.exit(1);
}

const rows = readFileSync(ROWS_FILE, 'utf8').split('\n').filter(Boolean).map((l) => JSON.parse(l));
// One row per id: the LAST record of a run wins (re-runs within one `npm test` overwrite).
const byId = new Map();
for (const r of rows) byId.set(r.id, r);
const date = new Date().toISOString().slice(0, 10);

const order = (id) => {
  const m = id.match(/^([A-Z]+)(\d+)(.*)$/);
  const series = { P: 0, T: 1, F: 2, G: 3, H: 4 }[m ? m[1] : 'Z'] ?? 9;
  return [series, m ? Number(m[2]) : 999, m ? m[3] : ''];
};
const sorted = [...byId.values()].sort((x, y) => {
  const [a1, a2, a3] = order(x.id); const [b1, b2, b3] = order(y.id);
  return a1 - b1 || a2 - b2 || (a3 < b3 ? -1 : a3 > b3 ? 1 : 0);
});

const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const table = (list) => [
  '| # | Persona | Attempt | HTTP / code | Body assertion | State assertion |',
  '|---|---|---|---|---|---|',
  ...list.map((r) => `| ${r.id} | ${esc(r.persona)} | ${esc(r.attempt)} | ${esc(r.status)} · ${esc(r.code)} | ${esc(r.body)} | ${esc(r.state)} |`),
].join('\n');

const header = (title) => TARGET === 'local' ? `# ${title} — LOCAL run, ${date}

Generated by \`npm test\` (scripts/evidence.mjs) from a single complete run against an in-process
parse-server 7.x (PostgreSQL adapter, port 5433, database \`llm_test\`) with EVERY provider call served by the
deterministic local simulator (scripts/simulator.mjs) — **LOCAL, SIMULATOR-BASED evidence only**. No real LLM
provider was called and no remote backend was touched; the Back4app + real-provider run of the same suites is
the live phase (coordinator-run) and produces its own file. Every assertion checks the response body AND the
database state (master-key read-back of LlmUsage), not just the status code. Budget outcomes are observations
of a BEST-EFFORT limiter, never guarantees.
` : `# ${title} — ${TARGET.toUpperCase()} run, ${date}

Generated by \`TEST_SERVER_URL=… npm test\` from a single complete run against
${TARGET === 'back4app' ? 'the Back4app backend' : 'a non-production rehearsal target'} with the App ID + REST/JS key + SETUP_TOKEN only —
state read-backs went through the token-gated Cloud function testInspect, never the master key. Every
assertion checks the response body AND the database state, not just the status code.
`;

writeFileSync(path.join(EVIDENCE_DIR, `matrix-${TARGET}-${date}.md`), `${header('askLlm test matrix')}
${table(sorted)}

## Live-only rows (not measured locally, by design)

| What | Why live-only |
|---|---|
| G1 function timeout value and aftermath on Back4app | the platform's limit is the platform's; locally only the proxy's own PROVIDER_TIMEOUT_MS is exercised |
| T13/T15 against the REAL provider (429 tier, platform 155 throttle interplay, H5) | needs the real provider key and the real plan; simulator rows above prove the mapping |
| §6.1 latency legs (a)/(b)/(c), §6.4 token costs, §6.6 quota math (H7) | real vantage, region, plan, model and PRICES VERIFIED ON THE DAY — placeholders are never published |
| T10 with a real throwaway key (only if the owner wants the direct "before" call shown) | key creation/revocation logged in the evidence file; the canary extraction above already proves extractability |

Suites in this run: ${[...new Set(sorted.map((r) => r.suite))].join(', ')} · ${sorted.length} matrix rows recorded at ${new Date().toISOString()}.
`);

console.log(`evidence: wrote matrix-${TARGET}-${date}.md (${sorted.length} rows)`);
for (const f of readdirSync(EVIDENCE_DIR).filter((f) => f.endsWith('.md') || f.endsWith('.csv')).sort()) console.log(`  docs/evidence/${f}`);
